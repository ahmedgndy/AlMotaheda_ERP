using System.Globalization;
using System.Net;
using System.Text;
using AlMotaheda.Modules.Reports.Contracts;
using ClosedXML.Excel;

namespace AlMotaheda.Modules.Reports.Engine;

/// <summary>Everything a file or a print page shows: the report, its filters, who made it and when, the rows and totals.</summary>
internal sealed record ReportDocument(
    ReportDefinition Definition,
    string Language,
    IReadOnlyDictionary<string, string> Filters,
    string GeneratedBy,
    DateTime GeneratedAtUtc,
    TimeZoneInfo CompanyZone,
    ReportData Data)
{
    public bool Arabic => Language == "ar";

    public string Title => Arabic ? Definition.NameAr : Definition.NameEn;

    public string ColumnTitle(ReportColumn column) => Arabic ? column.TitleAr : column.TitleEn;

    public string GeneratedAtLocal => TimeZoneInfo.ConvertTimeFromUtc(GeneratedAtUtc, CompanyZone).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture);

    public string FiltersLine => Filters.Count == 0
        ? (Arabic ? "بدون عوامل تصفية" : "No filters")
        : string.Join(" · ", Filters.Select(filter => $"{FilterLabel(filter.Key)}: {filter.Value}"));

    public string FileName => $"{Definition.Code}_{TimeZoneInfo.ConvertTimeFromUtc(GeneratedAtUtc, CompanyZone):yyyyMMdd_HHmm}.xlsx";

    private string FilterLabel(string name) =>
        Definition.Filters.FirstOrDefault(filter => filter.Name == name) is { } filter ? (Arabic ? filter.LabelAr : filter.LabelEn) : name;
}

/// <summary>The .xlsx file: a right-to-left sheet for Arabic, a header block, typed cells, a totals row, a frozen header.</summary>
internal static class ExcelReport
{
    private const string MoneyFormat = "#,##0.00";
    private const string QuantityFormat = "#,##0.###";
    private const string DateFormat = "yyyy-mm-dd";

    public static byte[] Write(ReportDocument document)
    {
        using var workbook = new XLWorkbook();
        var sheet = workbook.Worksheets.Add(document.Definition.Code);
        sheet.RightToLeft = document.Arabic;
        var columns = document.Definition.Columns;

        sheet.Cell(1, 1).Value = document.Title;
        sheet.Cell(1, 1).Style.Font.Bold = true;
        sheet.Cell(1, 1).Style.Font.FontSize = 14;
        sheet.Cell(2, 1).Value = document.FiltersLine;
        sheet.Cell(3, 1).Value = document.Arabic
            ? $"أعده: {document.GeneratedBy} · في: {document.GeneratedAtLocal}"
            : $"Generated by: {document.GeneratedBy} · at: {document.GeneratedAtLocal}";

        const int headerRow = 5;
        for (var index = 0; index < columns.Count; index++)
        {
            var cell = sheet.Cell(headerRow, index + 1);
            cell.Value = document.ColumnTitle(columns[index]);
            cell.Style.Font.Bold = true;
            cell.Style.Fill.BackgroundColor = XLColor.FromHtml("#E8ECF1");
        }

        var row = headerRow;
        foreach (var dataRow in document.Data.Rows)
        {
            row++;
            for (var index = 0; index < columns.Count; index++)
            {
                SetCell(sheet.Cell(row, index + 1), columns[index], dataRow.Cells.GetValueOrDefault(columns[index].Key));
            }
        }

        if (columns.Any(column => column.Total))
        {
            row++;
            var totals = ReportTotals.Of(document.Definition, document.Data.Rows);
            sheet.Cell(row, 1).Value = document.Arabic ? "الإجمالي" : "Total";
            for (var index = 0; index < columns.Count; index++)
            {
                if (totals.TryGetValue(columns[index].Key, out var total))
                {
                    SetCell(sheet.Cell(row, index + 1), columns[index], total);
                }
            }

            sheet.Row(row).Style.Font.Bold = true;
        }

        if (document.Data.Note is { } note)
        {
            sheet.Cell(row + 2, 1).Value = note;
        }

        sheet.SheetView.FreezeRows(headerRow);
        sheet.Columns(1, columns.Count).AdjustToContents(headerRow, row);

        using var stream = new MemoryStream();
        workbook.SaveAs(stream);
        return stream.ToArray();
    }

    private static void SetCell(IXLCell cell, ReportColumn column, object? value)
    {
        switch (value)
        {
            case null:
                return;
            case decimal amount:
                cell.Value = amount;
                cell.Style.NumberFormat.Format = column.Type == ReportColumnTypes.Quantity ? QuantityFormat : MoneyFormat;
                return;
            case int number:
                cell.Value = number;
                return;
            case DateOnly date:
                cell.Value = date.ToDateTime(TimeOnly.MinValue);
                cell.Style.NumberFormat.Format = DateFormat;
                return;
            default:
                // Text is stored as text, so a reference such as "00123" keeps its zeros.
                cell.Value = Convert.ToString(value, CultureInfo.InvariantCulture);
                return;
        }
    }
}

/// <summary>The print page: A4, right-to-left for Arabic, the same header, rows and totals as the Excel file.</summary>
internal static class PrintReport
{
    public static string Write(ReportDocument document)
    {
        var columns = document.Definition.Columns;
        var html = new StringBuilder();
        html.Append("<!doctype html><html lang=\"").Append(document.Language).Append("\" dir=\"").Append(document.Arabic ? "rtl" : "ltr").Append("\"><head><meta charset=\"utf-8\">");
        html.Append("<title>").Append(Encode(document.Title)).Append("</title><style>");
        html.Append("@page{size:A4 landscape;margin:12mm}body{font-family:Tahoma,Arial,sans-serif;font-size:11px;color:#111}");
        html.Append("h1{font-size:16px;margin:0 0 4px}p{margin:2px 0}table{border-collapse:collapse;width:100%;margin-top:8px}");
        html.Append("th,td{border:1px solid #999;padding:3px 5px}th{background:#e8ecf1}td.n{text-align:end;white-space:nowrap}");
        html.Append("tfoot td{font-weight:bold}thead{display:table-header-group}tr{page-break-inside:avoid}");
        html.Append("</style></head><body>");
        html.Append("<h1>").Append(Encode(document.Title)).Append("</h1>");
        html.Append("<p>").Append(Encode(document.FiltersLine)).Append("</p>");
        html.Append("<p>").Append(Encode(document.Arabic
            ? $"أعده: {document.GeneratedBy} · في: {document.GeneratedAtLocal}"
            : $"Generated by: {document.GeneratedBy} · at: {document.GeneratedAtLocal}")).Append("</p>");

        html.Append("<table><thead><tr>");
        foreach (var column in columns)
        {
            html.Append("<th>").Append(Encode(document.ColumnTitle(column))).Append("</th>");
        }

        html.Append("</tr></thead><tbody>");
        foreach (var row in document.Data.Rows)
        {
            html.Append("<tr>");
            foreach (var column in columns)
            {
                AppendCell(html, column, row.Cells.GetValueOrDefault(column.Key));
            }

            html.Append("</tr>");
        }

        html.Append("</tbody>");
        if (columns.Any(column => column.Total))
        {
            var totals = ReportTotals.Of(document.Definition, document.Data.Rows);
            html.Append("<tfoot><tr>");
            for (var index = 0; index < columns.Count; index++)
            {
                if (totals.TryGetValue(columns[index].Key, out var total))
                {
                    AppendCell(html, columns[index], total);
                }
                else
                {
                    html.Append("<td>").Append(index == 0 ? Encode(document.Arabic ? "الإجمالي" : "Total") : "").Append("</td>");
                }
            }

            html.Append("</tr></tfoot>");
        }

        html.Append("</table>");
        if (document.Data.Note is { } note)
        {
            html.Append("<p>").Append(Encode(note)).Append("</p>");
        }

        return html.Append("</body></html>").ToString();
    }

    private static void AppendCell(StringBuilder html, ReportColumn column, object? value)
    {
        var numeric = value is decimal or int;
        html.Append(numeric ? "<td class=\"n\">" : "<td>").Append(Encode(Format(column, value))).Append("</td>");
    }

    public static string Format(ReportColumn column, object? value) => value switch
    {
        null => "",
        decimal amount when column.Type == ReportColumnTypes.Quantity => amount.ToString("#,##0.###", CultureInfo.InvariantCulture),
        decimal amount => amount.ToString("#,##0.00", CultureInfo.InvariantCulture),
        int number => number.ToString(CultureInfo.InvariantCulture),
        DateOnly date => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "",
    };

    private static string Encode(string text) => WebUtility.HtmlEncode(text);
}
